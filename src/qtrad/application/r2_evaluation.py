def _verify_complete_local_ladder(
    verified: R1FoundationBindings,
    experiment: R2ExperimentConfig,
    local_result: LocalRidgeOofResult,
    feature_datasets: Sequence[R2FeatureDataset],
) -> None:
    declared = tuple(
        item
        for item in experiment.feature_sets
        if item.name not in {"P0", "P1"} and FeatureFamily.POOLED_CROSS_ASSET not in item.families
    )
    expected_feature_ids = {
        feature_set_id(
            experiment.configuration_id,
            item.name,
            feature_schema_for_set(experiment, item.name),
            experiment.market_data_source_class,
        )
        for item in declared
    }
    datasets_by_id = {dataset.feature_set_id: dataset for dataset in feature_datasets}
    if len(datasets_by_id) != len(feature_datasets) or set(datasets_by_id) != expected_feature_ids:
        raise ValueError(
            "local feature evidence does not cover the complete declared feature ladder"
        )
    expected = {
        (feature_id, instrument, fold.fold_id, experiment.primary_horizon)
        for feature_id in expected_feature_ids
        for instrument in experiment.target_instruments
        for fold in verified.folds.folds
    }
    actual = {
        (
            result.fit.feature_set_id,
            result.fit.target_instrument_id,
            result.fit.outer_fold_id,
            result.fit.horizon,
        )
        for result in local_result.fold_results
    }
    if actual != expected or len(actual) != len(local_result.fold_results):
        raise ValueError("local OOF evidence does not cover the complete declared feature ladder")
    for result in local_result.fold_results:
        verify_local_ridge_forecast_coverage(
            verified,
            datasets_by_id[result.fit.feature_set_id],
            experiment,
            result,
        )


def _expected_support(
    fold_results: Sequence[RidgeFoldResult],
    targets: Mapping[str, TargetRow],
) -> tuple[str, ...]:
    rows = tuple(row for result in fold_results for row in result.coverage.rows)
    keys = tuple((row.target_id, row.outer_fold_id) for row in rows)
    if len(set(keys)) != len(keys):
        raise ValueError("coverage repeats an expected target opportunity")
    if any(row.target_id not in targets for row in rows):
        raise ValueError("coverage includes unavailable, invalid or holdout target evidence")
    return tuple(sorted(row.target_id for row in rows))


def _fold_by_validation_target(
    verified: R1FoundationBindings,
    targets: Mapping[str, TargetRow],
) -> dict[str, str]:
    values = {
        target_id: fold.fold_id
        for fold in verified.folds.folds
        for target_id in fold.validation_target_ids
        if target_id in targets
    }
    if len(values) != sum(
        target_id in targets
        for fold in verified.folds.folds
        for target_id in fold.validation_target_ids
    ):
        raise ValueError("a target appears in more than one outer validation fold")
    return values


def _forecast_map(forecasts: ForecastDataset) -> dict[str, float]:
    values = {row.target_id: row.expected_return for row in forecasts.rows}
    if len(values) != len(forecasts.rows):
        raise ValueError("a model emitted more than one forecast for a target")
    return values


def _correlation_metric(
    left: Sequence[float],
    right: Sequence[float],
    minimum_rows: int,
    name: str,
) -> MetricValue:
    if len(left) < minimum_rows:
        return MetricValue.not_defined(f"{name} requires at least {minimum_rows} rows")
    left_std = pstdev(left)
    right_std = pstdev(right)
    if left_std == 0.0 or right_std == 0.0:
        return MetricValue.not_defined(f"{name} requires non-zero variance")
    return MetricValue.defined(_covariance(left, right) / (left_std * right_std))


def _covariance(left: Sequence[float], right: Sequence[float]) -> float:
    left_mean = fmean(left)
    right_mean = fmean(right)
    return fmean((x - left_mean) * (y - right_mean) for x, y in zip(left, right, strict=True))


def _ranks(values: Sequence[float]) -> tuple[float, ...]:
    indexed = sorted(enumerate(values), key=lambda item: item[1])
    ranks = [0.0] * len(values)
    position = 0
    while position < len(indexed):
        end = position + 1
        while end < len(indexed) and indexed[end][1] == indexed[position][1]:
            end += 1
        average_rank = (position + end - 1) / 2.0
        for index, _ in indexed[position:end]:
            ranks[index] = average_rank
        position = end
    return tuple(ranks)


def _mse(
    target_ids: Sequence[str],
    predictions: Mapping[str, float],
    targets: Mapping[str, TargetRow],
) -> float:
    return fmean(
        (predictions[target_id] - _not_none(targets[target_id].log_return)) ** 2
        for target_id in target_ids
    )


def _metric_difference(left: MetricValue, right: MetricValue) -> MetricValue:
    if left.value is None or right.value is None:
        return MetricValue.not_defined("metric difference requires two defined values")
    return MetricValue.defined(left.value - right.value)


def _metric_number(value: MetricValue) -> float:
    if value.value is None:
        raise ValueError("required selection metric is undefined")
    return value.value


def _positive_proportion(
    values: Sequence[tuple[str, float]],
    reason: str,
) -> MetricValue:
    if not values:
        return MetricValue.not_defined(reason)
    return MetricValue.defined(sum(value > 0 for _, value in values) / len(values))


def _best_contribution(
    values: Sequence[tuple[str, float]],
    reason: str,
) -> MetricValue:
    positive = [value for _, value in values if value > 0]
    if not positive:
        return MetricValue.not_defined(reason)
    return MetricValue.defined(max(positive) / sum(positive))


def _required_target(targets: Mapping[str, TargetRow], target_id: str) -> TargetRow:
    target = targets[target_id]
    if target.return_disposition is not ReturnDisposition.VALID or target.log_return is None:
        raise ValueError(f"target {target_id} is not valid evaluation evidence")
    return target


def _not_none(value: float | None) -> float:
    if value is None:
        raise ValueError("valid target unexpectedly lacks a realised return")
    return value


def _intersection(values: Sequence[set[str]]) -> set[str]:
    if not values:
        raise ValueError("support intersection requires at least one model")
    result = set(values[0])
    for value in values[1:]:
        result.intersection_update(value)
    return result


def _local_evaluation_model(
    local_result: LocalRidgeOofResult,
    feature_dataset: R2FeatureDataset,
) -> EvaluationModel:
    fold_results, forecasts = _local_scope(local_result, feature_dataset.feature_set_id)
    return EvaluationModel(
        ModelFamily.LOCAL_RIDGE,
        feature_dataset.feature_set_id,
        feature_dataset,
        forecasts,
        fold_results,
    )


def _local_scope(
    local_result: LocalRidgeOofResult,
    feature_set_id_value: str,
) -> tuple[tuple[RidgeFoldResult, ...], ForecastDataset]:
    fold_results = tuple(
        result
        for result in local_result.fold_results
        if result.fit.feature_set_id == feature_set_id_value
    )
    if not fold_results:
        raise ValueError("local comparator feature set has no fold-fit children")
    forecasts = ForecastDataset.create(
        tuple(row for result in fold_results for row in result.forecasts.rows),
        observation_dataset_id=local_result.forecasts.observation_dataset_id,
        panel_dataset_id=local_result.forecasts.panel_dataset_id,
        target_dataset_id=local_result.forecasts.target_dataset_id,
        fold_dataset_id=local_result.forecasts.fold_dataset_id,
    )
    return fold_results, forecasts
